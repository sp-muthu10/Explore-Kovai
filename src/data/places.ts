export function getCrowdColor(level: string): string {
  const l = level.toLowerCase();
  if (l.includes("very high") || l.includes("extremely high")) return "text-red-600";
  if (l.includes("high")) return "text-orange-500";
  if (l.includes("moderate")) return "text-yellow-500";
  if (l.includes("low")) return "text-green-500";
  return "text-muted-foreground";
}

